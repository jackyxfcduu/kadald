const assert=require('assert');
const core=require('../checker-core.js');
const patterns=Array.from({length:18},(_,i)=>({id:'P'+(i+1),name:'Pattern '+(i+1),ruleVersion:'test'}));
const symbols=['BTCUSDT','ETHUSDT','SOLUSDT']; const tfs=['W1','H4','M15','M5'];
const matrix=core.buildMatrix(symbols,tfs,patterns,'fixture-scan');
assert.equal(matrix.length,216,'3x4x18 matrix count');
for(const s of symbols)for(const tf of tfs)assert.equal(matrix.filter(x=>x.symbol===s&&x.timeframe===tf).length,18,`${s} ${tf} must have 18 checkers`);
const complete=matrix.map((x,i)=>core.finalize(x,i%18===0?'MATCH_FORMING':'NO_MATCH',{reason:'fixture'}));
assert.equal(core.verifyMatrix(complete,symbols,tfs,patterns).complete,true,'complete matrix must pass');
assert.equal(core.verifyMatrix(complete.slice(1),symbols,tfs,patterns).complete,false,'missing checker must fail');
assert.equal(core.verifyMatrix([...complete,complete[0]],symbols,tfs,patterns).complete,false,'duplicate checker must fail');
assert.equal(core.mapLegacyResult({status:'FORMING'}),'MATCH_FORMING');
assert.equal(core.mapLegacyResult({status:'DATA_ERROR'}),'DATA_ERROR');
assert.equal(core.mapLegacyResult({status:'NO_MATCH'},'SPECIFICATION_REQUIRED'),'SPECIFICATION_REQUIRED');
assert.throws(()=>core.finalize({},'FAKE_STATUS'),/Invalid checker status/);
console.log('PASS Phase 36.2 scan matrix core: 216 fixture checks; missing/duplicate detection; status mapping.');
