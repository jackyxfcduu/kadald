const assert=require('assert');
const fs=require('fs');
const root=__dirname+'/..';
const app=fs.readFileSync(root+'/app.js','utf8');
const engine=fs.readFileSync(root+'/ict-snr-engine.js','utf8');
assert(engine.includes('CONFIRMED_FVG_RETEST'),'engine should label confirmed retest entry model');
assert(engine.includes('bullRetest')&&engine.includes('bearRetest'),'engine must require directional FVG retest');
